import assert from 'node:assert/strict';
import * as THREE from 'three';
import {VRMStage} from '../src/renderer.js';
import {fitEnvironmentShadow} from '../src/environment-shadows.js';
const stage={visibleRecords:new Map([['left',{}],['right',{}]])};
const actor={vrm:{scene:new THREE.Group()},anchor:new THREE.Group()};
VRMStage.prototype.transformRecord.call(stage,actor,'left',{offsetZ:72});
assert.equal(actor.anchor.position.z,72);
assert.equal(actor.anchor.position.x,-1.22);
VRMStage.prototype.transformRecord.call(stage,actor,'right',{offsetZ:-88});
assert.equal(actor.anchor.position.z,-88);
assert.equal(actor.anchor.position.x,1.22);
const key=new THREE.DirectionalLight();
const bounds=new THREE.Box3(new THREE.Vector3(-20,-1,-30),new THREE.Vector3(25,18,75));
fitEnvironmentShadow(key,bounds);
assert.equal(key.castShadow,true);assert.equal(key.shadow.mapSize.x,2048);
assert.ok(key.shadow.camera.far>bounds.getSize(new THREE.Vector3()).length());
assert.ok(key.target.position.distanceTo(bounds.getCenter(new THREE.Vector3()))<1e-9);
let realShadow=false;
const context={environmentSettings:{},renderer:{shadowMap:{}},shadowLight:{},shadowPlane:{visible:true},keyLight:new THREE.DirectionalLight(),scene:new THREE.Scene(),element:{closest:()=>null},updateShadowGround(){realShadow=true;}};
VRMStage.prototype.applyShadowSettings.call(context);
assert.ok(realShadow&&context.renderer.shadowMap.enabled&&context.keyLight.castShadow);
assert.equal(context.shadowPlane.visible,false);assert.equal(context.shadowLight.castShadow,false);
const mesh=new THREE.Mesh(new THREE.BoxGeometry(),new THREE.MeshStandardMaterial());
context.renderSettings={shadowEnabled:false};VRMStage.prototype.applyShadowCasting.call(context,mesh);
assert.ok(mesh.castShadow&&mesh.receiveShadow);
console.log(JSON.stringify({ok:true,checks:['人物可前移72米及后移88米','多人物左右站位','真实阴影灯光覆盖场景','三维场景关闭旧阴影平面','人物投射并接收阴影']}));
